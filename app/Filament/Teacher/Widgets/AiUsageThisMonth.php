<?php

namespace App\Filament\Teacher\Widgets;

use App\Models\AiUsageLog;
use Filament\Widgets\StatsOverviewWidget as BaseWidget;
use Filament\Widgets\StatsOverviewWidget\Stat;

class AiUsageThisMonth extends BaseWidget
{
    protected static ?int $sort = 3;

    protected function getStats(): array
    {
        $userId = auth()->id();
        $monthStart = now()->startOfMonth();

        $usedThisMonth = AiUsageLog::where('user_id', $userId)
            ->where('created_at', '>=', $monthStart)
            ->where('status', '!=', 'failed')
            ->count();

        $todayUsed = AiUsageLog::where('user_id', $userId)
            ->where('created_at', '>=', now()->startOfDay())
            ->where('status', '!=', 'failed')
            ->count();

        $dailyLimit = (int) config('ai.limits.daily_per_user', 20);
        $remaining  = max(0, $dailyLimit - $todayUsed);

        $tokens = AiUsageLog::where('user_id', $userId)
            ->where('created_at', '>=', $monthStart)
            ->sum('output_tokens');

        return [
            Stat::make('Agent Quizzes · this month', $usedThisMonth)
                ->description('Generated by you')
                ->descriptionIcon('heroicon-m-cpu-chip')
                ->color('primary'),

            Stat::make('Daily quota left', $remaining . ' / ' . $dailyLimit)
                ->description($todayUsed . ' used today')
                ->descriptionIcon('heroicon-m-bolt')
                ->color($remaining > 5 ? 'success' : ($remaining > 0 ? 'warning' : 'danger')),

            Stat::make('Tokens used', number_format($tokens))
                ->description('Output tokens this month')
                ->descriptionIcon('heroicon-m-chart-pie')
                ->color('gray'),
        ];
    }
}
